  fun prayerName(key: PrayerKey): String =
    when (lang) {
      AppLanguage.RU ->
        when (key) {
          PrayerKey.FAJR -> "Фаджр"
          PrayerKey.ZUHR -> "Зухр"
          PrayerKey.ASR -> "Аср"
          PrayerKey.MAGHRIB -> "Магриб"
          PrayerKey.ISHA -> "Иша"
        }
      AppLanguage.UZ ->
        when (key) {
          PrayerKey.FAJR -> "Bomdod"
          PrayerKey.ZUHR -> "Peshin"
          PrayerKey.ASR -> "Asr"
          PrayerKey.MAGHRIB -> "Shom"
          PrayerKey.ISHA -> "Xufton"
        }
    }

  fun categoryLabel(cat: AnalysisCategory): String =
    when (cat) {
      AnalysisCategory.LIMBS -> categoryLimbsLabel
      AnalysisCategory.HEART -> categoryHeartLabel
    }

  fun categoryBadge(cat: AnalysisCategory): String =
    when (cat) {
      AnalysisCategory.LIMBS -> categoryLimbsBadge
      AnalysisCategory.HEART -> categoryHeartBadge
    }

  fun defaultBookTitleOrCustom(id: String, storedTitle: String): String {
    if (lang == AppLanguage.RU) return storedTitle
    return when {
      id == "b1" && storedTitle == "Очищение души" -> "Nafsni poklash"
      id == "b2" && storedTitle == "Сады праведных" -> "Solihlar gulshani"
      else -> storedTitle
    }
  }

  fun defaultQuestionTextOrCustom(id: String, storedText: String): String {
    if (lang == AppLanguage.RU) return storedText
    val map =
      mapOf(
        "q1" to ("Произносил ли язык сплетни?" to "Til g‘iybat qildimi?"),
        "q2" to ("Произносил ли язык ложь?" to "Til yolg‘on gapirdimi?"),
        "q3" to ("Слушали ли уши запретное?" to "Quloqlar haromni eshitdimi?"),
        "q4" to ("Смотрели ли глаза на запретное?" to "Ko‘zlar haromga qaradimi?"),
        "q5" to ("Были ли греховные мысли?" to "Gunohli fikrlar bo‘ldimi?"),
        "q6" to ("Была ли показуха (рия) в моих действиях?" to "Amallarimda riyo (xo‘jako‘rsin) bo‘ldimi?"),
        "q7" to ("Было ли самолюбование (уджб)?" to "O‘ziga bino qo‘yish (ujb) bo‘ldimi?"),
        "q8" to ("Было ли высокомерие?" to "Kibr bo‘ldimi?"),
        "q9" to ("Была ли жадность?" to "Xasislik (ochko‘zlik) bo‘ldimi?"),
        "q10" to ("Был ли гнев?" to "G‘azab bo‘ldimi?"),
        "q11" to ("Была ли обида у меня?" to "Menda xafagarchilik (gina) bo‘ldimi?"),
      )
    val pair = map[id]
    return if (pair != null && storedText == pair.first) pair.second else storedText
  }
}

